export const formatTime12h = (time) => {
  if (typeof time !== 'string') return '';
  const value = time.trim();
  const match = /^(\d{1,2}):([0-5]\d)(?::[0-5]\d)?(?:\s*(AM|PM))?$/i.exec(value);
  if (!match) return value;

  const [, hourText, minute, period] = match;
  const hour = Number(hourText);
  if (hour > 23 || (period && (hour < 1 || hour > 12))) return value;

  const displayHour = String(hour % 12 || 12).padStart(2, '0');
  const suffix = period ? period.toUpperCase() : hour >= 12 ? 'PM' : 'AM';
  return `${displayHour}:${minute} ${suffix}`;
};

